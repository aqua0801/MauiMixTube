using System;

namespace MauiMixTube.Generators
{
    using System.Collections.Generic;
    using System.Linq;
    using System.Text;
    using Microsoft.CodeAnalysis;
    using Microsoft.CodeAnalysis.CSharp.Syntax;
    using Microsoft.CodeAnalysis.Text;


    [Generator]
    public class WebTagGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var tagged = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    "MauiMixTube.Models.WebTagProviderAttribute",
                    predicate: (node, _) => node is ClassDeclarationSyntax,
                    transform: (ctx, _) => GetTagNames(ctx))
                .Collect();

            context.RegisterSourceOutput(tagged, GenerateSource);
        }

