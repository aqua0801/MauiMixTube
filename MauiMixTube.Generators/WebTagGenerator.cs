        //}
        private static IEnumerable<string> GetTagNames(GeneratorAttributeSyntaxContext ctx)
        {
            var classNode = (ClassDeclarationSyntax)ctx.TargetNode;
            var model = ctx.SemanticModel;
            var results = new List<string>();

            foreach (var member in classNode.Members)
            {
                if (member is FieldDeclarationSyntax field)
                {
                    var typeInfo = model.GetTypeInfo(field.Declaration.Type).Type;
                    if (typeInfo?.Name == "WebTag")
                    {
                        foreach (var v in field.Declaration.Variables)
                            results.Add(v.Identifier.Text);
                    }
                }
                else if (member is PropertyDeclarationSyntax property)
                {
                    var typeInfo = model.GetTypeInfo(property.Type).Type;
                    if (typeInfo?.Name == "WebTag")
                    {
                        results.Add(property.Identifier.Text);
                    }
                }
            }
            return results;
        }

        private static void GenerateSource(
            SourceProductionContext ctx,
            System.Collections.Immutable.ImmutableArray<IEnumerable<string>> tagGroups)
        {
            var tagNames = tagGroups.SelectMany(t => t).Distinct();

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("namespace MauiMixTube.Models;");
            sb.AppendLine();
            sb.AppendLine("public partial record WebTag");
            sb.AppendLine("{");

            foreach (var name in tagNames)
                sb.AppendLine($"    public static WebTag {name} => WebTagRegistry.GetByName(\"{name}\");");

            sb.AppendLine("}");

            ctx.AddSource("WebTag.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }
}
